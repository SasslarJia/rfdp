"""Compute and independently read back official, full-gallery MSMT17 rankings."""
import argparse
import os
import shutil
import time
from pathlib import Path

import numpy as np

from EVAL.ReIDEval import _evaluate_details
from .extract import COUNTS, TOTAL, block_hash, read_json, save_json, validate_rows, verify_one, writer
from .models import SPECS, digest


def frozen_input(root, backbone):
    meta = read_json(root / "dataset.json")
    handoff = read_json(root / "HANDOFF.json")
    manifest = root / "image-manifest.json"
    folder = root / backbone
    if (meta["version"] != "V2" or meta["counts"] != COUNTS
            or digest(manifest) != meta["manifest_sha256"]
            or digest(root / "dataset.json") != handoff["dataset_sha256"]
            or digest(folder / "COMPLETE.json") != handoff["receipts"][backbone]):
        raise ValueError("Frozen dataset or feature receipt differs from the CUDA handoff")
    rows = read_json(manifest)
    validate_rows(rows)
    receipt = verify_one(folder, backbone, meta)
    if receipt["feature_sha256"] != handoff["features"][backbone]:
        raise ValueError("Feature matrix differs from the CUDA handoff")
    feature_path = folder / "features.npy"
    binding = dict(backbone=backbone, feature_sha256=receipt["feature_sha256"],
                   image_manifest_sha256=meta["manifest_sha256"],
                   handoff_sha256=digest(root / "HANDOFF.json"))
    return feature_path, rows, binding


def checked_row(row, q_pid, q_cam, gallery_pid, gallery_cam, offset, cmc_depth):
    """Check the full permutation and compare the evaluator with hit-position formulas."""
    g = len(gallery_pid)
    if row.shape != (g,) or row.dtype != np.int32:
        raise ValueError("Expected one int32 global ID per gallery entry")
    ids = row - offset
    if ids.min() < 0 or ids.max() >= g or not np.all(np.bincount(ids, minlength=g) == 1):
        raise ValueError("Gallery row is not a complete permutation")
    cmc, ap, inp, valid, relevant, found = _evaluate_details(
        ids, q_pid, q_cam, gallery_pid, gallery_cam, cmc_depth)
    if not valid or found != relevant:
        raise ValueError("Expected every official MSMT17 query to retrieve all eligible positives")
    ordered_pid = gallery_pid[ids]
    eligible = (ordered_pid != -1) & ((ordered_pid != q_pid) | (gallery_cam[ids] != q_cam))
    positions = np.flatnonzero(ordered_pid[eligible] == q_pid) + 1
    first, last = int(positions[0]), int(positions[-1])
    if (len(positions) != relevant or abs(ap - np.mean(np.arange(1, relevant+1) / positions)) > 1e-12
            or abs(inp - relevant / last) > 1e-12
            or not np.array_equal(cmc, np.arange(1, cmc_depth+1) >= first)):
        raise ValueError("Official metrics disagree with positive hit positions")
    return dict(pid=int(q_pid), camid=int(q_cam), AP=ap, INP=inp, rank1=int(first==1),
                first_positive=first, last_positive=last, positive_count=relevant)


def accept_ranking(path, rows, output, binding, block_digests):
    query_count, gallery_count = COUNTS["query"], COUNTS["gallery"]
    ranks = np.load(path, mmap_mode="r", allow_pickle=False)
    if ranks.shape != (query_count, gallery_count) or ranks.dtype != np.int32:
        raise ValueError("Full ranking shape or type mismatch")
    pids = np.array([r["pid"] for r in rows], dtype=np.int32)
    cameras = np.array([r["camid"] for r in rows], dtype=np.int32)
    details = []
    start = 0
    for end, expected in block_digests:
        if not start < end <= query_count or block_hash(ranks[start:end]) != expected:
            raise ValueError("Saved ranking block differs from the generated bytes")
        for q in range(start, end):
            result = checked_row(ranks[q], pids[q], cameras[q], pids[query_count:],
                                 cameras[query_count:], query_count, 500)
            details.append(dict(query_id=q, **result))
        start = end
    if start != query_count:
        raise ValueError("Incomplete ranking evidence")
    first = np.array([item["first_positive"] for item in details])
    cmc = np.cumsum(np.bincount(first, minlength=gallery_count+1))[1:] / query_count
    metrics = dict(valid_queries=query_count, mAP=float(np.mean([r["AP"] for r in details])),
                   mINP=float(np.mean([r["INP"] for r in details])), cmc=cmc.tolist())
    metrics.update({f"rank-{k}": float(cmc[k-1]) for k in (1, 5, 10, 20)})
    save_json(output / "metrics.json", metrics)
    save_json(output / "per-query.json", details)
    return dict(binding=binding, queries=query_count, gallery=gallery_count, valid_queries=query_count,
                full_gallery_permutations=query_count, checked_metrics=query_count,
                ranking_sha256=digest(path), ranking_bytes=path.stat().st_size,
                metrics_sha256=digest(output / "metrics.json"), per_query_sha256=digest(output / "per-query.json"))


def raw_cosine(root, backbone, output, path, block_rows=64):
    with writer(output):
        started = time.monotonic()
        feature_path, rows, binding = frozen_input(root, backbone)
        binding.update(method="raw-cosine", normalization="float64 L2",
                       ties="ascending global gallery id", block_rows=block_rows,
                       runner_sha256=digest(__file__))
        if (output / "FULL_ACCEPTANCE.json").is_file():
            receipt = read_json(output / "FULL_ACCEPTANCE.json")
            if (receipt["binding"] != binding or digest(path) != receipt["ranking_sha256"]
                    or any(digest(output / f) != receipt[key] for f, key in
                           (("metrics.json", "metrics_sha256"), ("per-query.json", "per_query_sha256")))):
                raise ValueError("Completed cell has different input or output")
            return
        qn, gn = COUNTS["query"], COUNTS["gallery"]
        path.parent.mkdir(parents=True, exist_ok=True)
        progress_path = output / "progress.json"
        if progress_path.exists():
            progress = read_json(progress_path)
            if progress["binding"] != binding:
                raise ValueError("A different input or raw definition owns this checkpoint")
            ranks = np.load(path, mmap_mode="r+", allow_pickle=False)
            if ranks.shape != (qn, gn) or ranks.dtype != np.int32:
                raise ValueError("Invalid ranking checkpoint shape")
        else:
            if path.exists():
                raise FileExistsError(path)
            total, _, free = shutil.disk_usage(path.parent)
            if free - (qn * gn * 4 + 4096) < max(total//4, 10*1024**3):
                raise OSError("Ranking storage would infringe the disk reserve")
            ranks = np.lib.format.open_memmap(path, mode="w+", dtype=np.int32, shape=(qn, gn))
            progress = dict(binding=binding, blocks=[], compute_s=0., write_s=0.)
            save_json(progress_path, progress)
        start = 0
        for end, expected in progress["blocks"]:
            if not start < end <= qn or block_hash(ranks[start:end]) != expected:
                raise ValueError("Checkpoint block checksum mismatch")
            start = end
        tick = time.monotonic()
        features = np.load(feature_path, mmap_mode="r", allow_pickle=False).astype(np.float64)
        for lo in range(0, TOTAL, 1024):
            part = features[lo:lo+1024]
            part /= np.linalg.norm(part, axis=1, keepdims=True)
        progress["compute_s"] += time.monotonic()-tick
        for lo in range(start, qn, block_rows):
            hi = min(qn, lo+block_rows)
            tick = time.monotonic()
            scores = features[lo:hi] @ features[qn:].T
            if not np.isfinite(scores).all():
                raise ValueError("Nonfinite cosine similarity")
            scores *= -1
            ordered = np.argsort(scores, axis=1, kind="stable").astype(np.int32)
            ordered += qn
            progress["compute_s"] += time.monotonic()-tick
            tick = time.monotonic()
            ranks[lo:hi] = ordered
            ranks.flush()
            progress["blocks"].append([hi, block_hash(ordered)])
            progress["write_s"] += time.monotonic()-tick
            save_json(progress_path, progress)
        del ranks, features
        tick = time.monotonic()
        receipt = accept_ranking(path, rows, output, binding, progress["blocks"])
        receipt.update(compute_s=progress["compute_s"], save_s=progress["write_s"],
                       readback_s=time.monotonic()-tick, current_process_wall_s=time.monotonic()-started,
                       ranking_path=str(path.resolve()), blas_threads=os.environ.get("OPENBLAS_NUM_THREADS"))
        save_json(output / "FULL_ACCEPTANCE.json", receipt)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--frozen", type=Path, required=True)
    parser.add_argument("--backbone", choices=SPECS, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--ranking", type=Path, required=True)
    args = parser.parse_args()
    raw_cosine(args.frozen, args.backbone, args.output, args.ranking)
